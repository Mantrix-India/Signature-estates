import { z } from 'zod';

/* ───────────────────────── sanitising helpers ───────────────────────── */

// C0/C1 control characters except \n (keeps line breaks in messages).
const CONTROL_CHARS = /[\u0000-\u0009\u000B-\u001F\u007F-\u009F]/g;
const ZERO_WIDTH = /[\u200B-\u200F\u2028-\u202E\u2060-\u206F\uFEFF]/g;

/** Strip control/zero-width chars and any HTML tags, normalise whitespace. */
export function cleanText(value: string, { multiline = false } = {}): string {
  let v = value.normalize('NFC').replace(CONTROL_CHARS, '').replace(ZERO_WIDTH, '');
  v = v.replace(/<[^>]*>/g, '').replace(/[<>]/g, '');
  if (multiline) {
    v = v
      .replace(/\r\n?/g, '\n')
      .replace(/[ \t]+/g, ' ')
      .replace(/\n{3,}/g, '\n\n');
  } else {
    v = v.replace(/\s+/g, ' ');
  }
  return v.trim();
}

/**
 * Indian mobile -> canonical 10 digits. Accepts "+91 98765 43210",
 * "09876543210", "919876543210", "98765-43210". Returns null if invalid.
 */
export function normalizeIndianPhone(raw: string): string | null {
  let digits = raw.replace(/\D/g, '');
  if (digits.length === 12 && digits.startsWith('91')) digits = digits.slice(2);
  else if (digits.length === 11 && digits.startsWith('0')) digits = digits.slice(1);
  return /^[6-9]\d{9}$/.test(digits) ? digits : null;
}

/* ───────────────────────────── listings ───────────────────────────── */

const shortText = z
  .string()
  .max(100)
  .transform((v) => cleanText(v))
  .pipe(z.string().min(1).max(100));

export const PUBLIC_SORTS = ['newest', 'price_asc', 'price_desc', 'area_desc', 'area_asc'] as const;

/**
 * Only these keys are read. There is deliberately NO isPublished/status key:
 * visibility is hard-coded in the service, so no query string can widen it.
 * Repeated keys (?city=a&city=b) arrive as arrays and are rejected.
 */
export const publicListQuerySchema = z.object({
  page: z.coerce.number().int().min(1).max(500).default(1),
  limit: z.coerce.number().int().min(1).max(48).default(12),
  locality: shortText.optional(),
  city: shortText.optional(),
  propertyType: z.enum(['APARTMENT', 'VILLA', 'PLOT', 'COMMERCIAL', 'OTHER']).optional(),
  listingType: z.enum(['SALE', 'RENT']).optional(),
  minPrice: z.coerce.number().nonnegative().max(1e11).optional(),
  maxPrice: z.coerce.number().positive().max(1e11).optional(),
  bedrooms: z.coerce.number().int().min(0).max(20).optional(),
  furnishing: z.enum(['UNFURNISHED', 'SEMI_FURNISHED', 'FURNISHED']).optional(),
  possessionStatus: z.enum(['READY_TO_MOVE', 'UNDER_CONSTRUCTION']).optional(),
  /** Comma separated, matched with "has every". */
  amenities: z
    .string()
    .max(500)
    .transform((v) =>
      v
        .split(',')
        .map((a) => cleanText(a))
        .filter((a) => a.length > 0 && a.length <= 60)
        .slice(0, 10)
    )
    .optional(),
  sort: z.enum(PUBLIC_SORTS).default('newest'),
});

export type PublicListQuery = z.infer<typeof publicListQuerySchema>;

/** Slugs are generated by us: lowercase a-z, 0-9 and '-'. Anything else is a 404. */
export const publicSlugSchema = z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/).max(100);

/* ───────────────────────────── enquiries ───────────────────────────── */

export const ENQUIRY_TYPES = ['GENERAL', 'SITE_VISIT', 'CALLBACK', 'BROCHURE', 'PRICE_REQUEST'] as const;
export const PREFERRED_SLOTS = ['MORNING', 'AFTERNOON', 'EVENING'] as const;

/** Name of the honeypot field. Real users never see or fill it. */
export const HONEYPOT_FIELD = 'companyWebsite';

const optionalEmpty = (v: unknown) => (typeof v === 'string' && v.trim() === '' ? undefined : v);

const preferredDateSchema = z
  .union([z.iso.date(), z.iso.datetime({ offset: true })])
  .refine(
    (v) => {
      const d = new Date(v.length === 10 ? `${v}T23:59:59+05:30` : v);
      const now = Date.now();
      return d.getTime() >= now - 60_000 && d.getTime() <= now + 180 * 24 * 3600 * 1000;
    },
    { message: 'Preferred date must be today or within the next 6 months' }
  );

export const publicEnquirySchema = z
  .object({
    fullName: z
      .string()
      .max(200)
      .transform((v) => cleanText(v))
      .pipe(
        z
          .string()
          .min(2, 'Please enter your full name')
          .max(100)
          .regex(/^[\p{L}\p{M} .'-]+$/u, 'Name can only contain letters, spaces, . \' and -')
      ),
    phone: z
      .string()
      .max(20)
      .transform((v, ctx) => {
        const phone = normalizeIndianPhone(v);
        if (!phone) {
          ctx.addIssue({ code: 'custom', message: 'Enter a valid 10-digit Indian mobile number' });
          return z.NEVER;
        }
        return phone;
      }),
    email: z.preprocess(
      optionalEmpty,
      z.string().trim().toLowerCase().max(254).email('Enter a valid email address').optional()
    ),
    message: z.preprocess(
      optionalEmpty,
      z
        .string()
        .max(4000)
        .transform((v) => cleanText(v, { multiline: true }))
        .pipe(z.string().max(2000, 'Message is too long'))
        .optional()
    ),
    propertyId: z.preprocess(optionalEmpty, z.string().uuid('Invalid property').optional()),
    enquiryType: z.enum(ENQUIRY_TYPES),
    preferredDate: z.preprocess(optionalEmpty, preferredDateSchema.optional()),
    preferredSlot: z.preprocess(optionalEmpty, z.enum(PREFERRED_SLOTS).optional()),
    [HONEYPOT_FIELD]: z.string().max(500).optional(),
  })
  .strict();

export type PublicEnquiryInput = z.infer<typeof publicEnquirySchema>;
